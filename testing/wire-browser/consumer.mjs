// Consumer DTO qualification is separate from the production endpoint baseline.
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export async function checkConsumer(out) {
  const { consumer_echo: codec } = await import(pathToFileURL(resolve(out, 'compiled/consumer.js')));
  const { WireError } = await import(pathToFileURL(resolve(out, 'compiled/native-runtime.js')));
  const { value, request, response } = await import(pathToFileURL(resolve(out, 'consumer-vectors.mjs')));
  const refused = action => assert.throws(action, WireError);
  // Exact frames are generated by native Serde, independently of TypeScript.
  for (const [encode, decode, bytes] of [
    [codec.encodeRequest, codec.decodeRequest, request],
    [codec.encodeResponse, codec.decodeResponse, response],
  ]) {
    assert.deepEqual(encode(value), bytes);
    assert.deepEqual(encode(value), bytes, 'same value retains exact retry bytes');
    const decoded = decode(bytes);
    assert.equal(Object.getPrototypeOf(decoded), null);
    assert.deepEqual({ ...decoded }, value);
    for (let cut = 0; cut < bytes.length; cut++) refused(() => decode(bytes.slice(0, cut)));
    refused(() => decode(new Uint8Array([...bytes, 0])));
    refused(() => encode({ ...value, blob: new Uint8Array(512) }));
    refused(() => encode({ ...value, blob: [0, 128, 255] }));
    refused(() => encode({ ...value, id: 7 }));
    refused(() => encode({ ...value, unit: undefined }));
    refused(() => encode({ ...value, ulid: new Uint8Array(15) }));
    refused(() => encode({ ...value, amount: '01.23' }));
    const invalidText = bytes.slice();
    const text = new TextEncoder().encode(value.address);
    const offset = bytes.findIndex((_, i) => text.every((byte, j) => bytes[i + j] === byte));
    assert.ok(offset >= 0);
    invalidText[offset] = 255;
    refused(() => decode(invalidText));
    // Empty/nonempty byte strings and the concrete endpoint's exact ceiling.
    let maximum = 0;
    for (let length = 0; length <= 512; length++) {
      const candidate = { ...value, blob: new Uint8Array(length) };
      try {
        const frame = encode(candidate);
        assert.deepEqual({ ...decode(frame) }, candidate);
        maximum = length;
      } catch (error) {
        assert.ok(error instanceof WireError);
        assert.equal(error.code, 'limit');
        assert.equal(length, maximum + 1);
        break;
      }
    }
    assert.ok(maximum > 0);
  }
  refused(() => codec.decodeResponse(request));
  refused(() => codec.decodeRequest(response));
  console.log('Consumer DTO Rust/TypeScript frames, scalar families and bounded refusals passed');
}
